#!/usr/bin/env python3
"""AI-assisted: bakes a multi-size bitmap font atlas for pixel-exact text.

Usage (from the repository root):
    python3 -I tools/generate_font_atlas.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf data/fonts

Writes data/fonts/dejavu_mono_atlas.png (8-bit coverage) and
data/fonts/dejavu_mono_atlas.txt (metrics). Each size is rasterized by
FreeType (through Pillow) with the font's hinting, at the exact pixel size it
is drawn on screen, so src/ui/textrendering.cpp can draw it 1:1 without
resampling. Only Pillow is required.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZES = list(range(8, 33)) + [36, 40, 44, 48, 56, 64]   # Pixel sizes (em).
FIRST, LAST = 32, 126
PAD = 2              # Empty texels around each glyph: room for the 1 px outline.
ATLAS_WIDTH = 2048


def rasterize(font, code):
    """Glyph coverage cropped to its ink, with the offset from the pen."""
    ch = chr(code)
    size = font.size
    canvas = Image.new("L", (size * 3, size * 3), 0)
    origin = (size, 2 * size)                      # Pen position (baseline).
    ImageDraw.Draw(canvas).text(origin, ch, font=font, fill=255, anchor="ls")
    box = canvas.getbbox()
    if box is None:                                # Space.
        return None, 0, 0
    glyph = canvas.crop(box)
    return glyph, box[0] - origin[0], origin[1] - box[1]   # left, top (Y up)


def main(font_path, out_dir):
    entries = []
    for size in SIZES:
        font = ImageFont.truetype(font_path, size)
        ascent, descent = font.getmetrics()
        for code in range(FIRST, LAST + 1):
            image, left, top = rasterize(font, code)
            entries.append((size, code, image, left, top, font.getlength(chr(code)), ascent, descent))
    # Shelf packing, tallest first so shelves are tight.
    order = sorted(range(len(entries)), key=lambda i: -(entries[i][2].height if entries[i][2] else 0))
    x = y = shelf = 0
    place = {}
    for i in order:
        image = entries[i][2]
        w = (image.width if image else 0) + 2 * PAD
        h = (image.height if image else 0) + 2 * PAD
        if x + w > ATLAS_WIDTH:
            x, y, shelf = 0, y + shelf, 0
        place[i] = (x + PAD, y + PAD)
        x += w
        shelf = max(shelf, h)
    height = 1
    while height < y + shelf:
        height *= 2
    atlas = Image.new("L", (ATLAS_WIDTH, height), 0)
    for i, (px, py) in place.items():
        if entries[i][2]:
            atlas.paste(entries[i][2], (px, py))
    atlas.save(out_dir + "/dejavu_mono_atlas.png", optimize=True)
    with open(out_dir + "/dejavu_mono_atlas.txt", "w") as out:
        out.write("# GENERATED by tools/generate_font_atlas.py -- AI-assisted.\n")
        out.write("# DejaVu Sans Mono 2.37 rasterized by FreeType (Pillow), hinted, 8-bit coverage.\n")
        out.write("# atlas <width> <height>\n# size <px> <ascent> <descent>\n")
        out.write("# glyph <code> <x> <y> <w> <h> <left> <top> <advance>  (pixels; top = above baseline)\n")
        out.write("atlas %d %d\n" % (ATLAS_WIDTH, height))
        current = None
        for i, (size, code, image, left, top, advance, ascent, descent) in enumerate(entries):
            if size != current:
                out.write("size %d %d %d\n" % (size, ascent, descent))
                current = size
            px, py = place[i]
            w, h = (image.width, image.height) if image else (0, 0)
            out.write("glyph %d %d %d %d %d %d %d %.4f\n" % (code, px, py, w, h, left, top, advance))
    print("atlas %dx%d, %d sizes, %d glyphs" % (ATLAS_WIDTH, height, len(SIZES), len(entries)))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
